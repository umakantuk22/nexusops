/**
 * Project Nexus - Business Workflow Rules Engine
 */
import { OutboxService } from './outbox.service.js';
import { ActivityService } from '../crm/activity.service.js';
import { logger } from '../../lib/logger.js';

export class WorkflowEngine {
  /**
   * Evaluates domain events and executes automated workflow rules.
   */
  static async handleEvent(event) {
    const { organizationId, eventType, payload } = event;

    // Rule 1: When an Opportunity is WON and value >= $50,000, schedule high-priority Executive Welcome task
    if (eventType === 'OpportunityWon' && payload.value >= 50000) {
      logger.info('Workflow Rule Triggered: High Value Deal Won', { oppId: payload.opportunityId, value: payload.value });
      
      return await ActivityService.createActivity({
        organizationId,
        userId: payload.userId,
        entityType: 'Account',
        entityId: payload.accountId,
        type: 'TASK',
        subject: `Executive Onboarding Welcome: Deal $${payload.value}`,
        description: 'Auto-generated by Nexus Workflow Engine for Tier 1 Enterprise Deal.',
        dueDate: new Date(Date.now() + 24 * 60 * 60 * 1000), // Within 24 hours
      });
    }

    return null;
  }
}
